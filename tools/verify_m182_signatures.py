def va_to_raw(va):
    for name, sva, vsize, raw, rsize in SECTIONS:
        if sva <= va < sva + max(vsize, rsize):
            return raw + (va - sva)
    return None


def find_all(data, needle):
    out = []
    o = 0
    while True:
        i = data.find(needle, o)
        if i < 0:
            break
        out.append(i)
        o = i + 1
    return out


def raw_to_va(raw):
    for name, sva, vsize, sraw, rsize in SECTIONS:
        if sraw <= raw < sraw + rsize:
            return sva + (raw - sraw)
    return None


